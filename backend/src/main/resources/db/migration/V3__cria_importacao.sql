CREATE TABLE importacao (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                 VARCHAR(20)  NOT NULL,
    nome_arquivo         VARCHAR(255) NOT NULL,
    status               VARCHAR(20)  NOT NULL,
    quantidade_total     INTEGER      NOT NULL DEFAULT 0,
    quantidade_importada INTEGER      NOT NULL DEFAULT 0,
    quantidade_ignorada  INTEGER      NOT NULL DEFAULT 0,
    quantidade_com_erro  INTEGER      NOT NULL DEFAULT 0,
    criado_por           VARCHAR(150) NOT NULL,
    atualizado_por       VARCHAR(150) NOT NULL,
    criado_em            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE importacao_item (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    importacao_id         BIGINT       NOT NULL REFERENCES importacao (id) ON DELETE CASCADE,
    linha_origem          INTEGER      NOT NULL,
    rm_extraido           INTEGER,
    nome_extraido         VARCHAR(255),
    status                VARCHAR(20)  NOT NULL,
    mensagem_erro         VARCHAR(500),
    registro_matricula_id BIGINT       REFERENCES registro_matricula (id)
);

CREATE INDEX idx_item_importacao ON importacao_item (importacao_id);
