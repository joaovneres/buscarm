CREATE TABLE registro_matricula (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rm            INTEGER      NOT NULL,
    nome_completo VARCHAR(255) NOT NULL,
    sobrenome     VARCHAR(255) NOT NULL,
    nome_busca    VARCHAR(255) NOT NULL,
    ano_registro   INTEGER,
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_por     VARCHAR(150) NOT NULL,
    atualizado_por VARCHAR(150) NOT NULL,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_registro_rm UNIQUE (rm)
);

-- Índice para busca por nome normalizado (acento/caixa-insensível via coluna nome_busca).
CREATE INDEX idx_registro_nome_busca ON registro_matricula (nome_busca);
-- Índice para ordenação/listagem por sobrenome.
CREATE INDEX idx_registro_sobrenome ON registro_matricula (sobrenome);
